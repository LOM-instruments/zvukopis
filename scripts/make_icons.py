#!/usr/bin/env python3
"""Makes src/icons.h: Lucide icons (https://lucide.dev, ISC) as 1-bit bitmaps
for the e-paper screen, drawn with Adafruit GFX's drawXBitmap().

    python3 scripts/make_icons.py

Needs resvg and ImageMagick (brew install resvg imagemagick). Each icon is
fetched from the lucide-static package at the version below, rendered at the
size the screen uses (the 2 px stroke of the 24 px original scales with it),
and thresholded to black and white. Add an icon to ICONS and run again.
"""

import os
import subprocess
import sys
import tempfile
import urllib.request

LUCIDE_VERSION = "0.468.0"
# (lucide name, size in pixels, C identifier)
ICONS = [
    ("mic", 112, "IconMic"),
    ("wifi", 96, "IconWifi"),
]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def xbm_bits(xbm):
    body = xbm[xbm.index("{") + 1 : xbm.rindex("}")]
    return [int(t, 16) for t in body.replace("\n", " ").split(",") if t.strip()]


def main():
    out = ["#pragma once", "",
           "// Icons from Lucide (https://lucide.dev), ISC licence, as 1-bit bitmaps for",
           "// Adafruit GFX drawXBitmap(). Generated by scripts/make_icons.py (lucide-static",
           f"// {LUCIDE_VERSION}); don't edit.", "", "#include <Arduino.h>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name, size, ident in ICONS:
            url = f"https://unpkg.com/lucide-static@{LUCIDE_VERSION}/icons/{name}.svg"
            svg = os.path.join(tmp, name + ".svg")
            png = os.path.join(tmp, name + ".png")
            urllib.request.urlretrieve(url, svg)
            subprocess.run(["resvg", "-w", str(size), "-h", str(size), svg, png], check=True)
            xbm = subprocess.run(["magick", png, "-background", "white", "-alpha", "remove", "-threshold", "50%", "xbm:-"],
                                 check=True, capture_output=True, text=True).stdout
            bits = xbm_bits(xbm)
            assert len(bits) == (size + 7) // 8 * size, (name, len(bits))
            out.append(f"// {name}, {size} x {size}")
            out.append(f"static const int {ident}Size = {size};")
            out.append(f"static const uint8_t {ident}[] PROGMEM = {{")
            for i in range(0, len(bits), 16):
                out.append("    " + ", ".join(f"0x{b:02X}" for b in bits[i : i + 16]) + ",")
            out.append("};")
            out.append("")
            print(f"{name}: {size} px, {len(bits)} bytes, {sum(bin(b).count('1') for b in bits)} ink pixels")
    path = os.path.join(ROOT, "src", "icons.h")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    sys.exit(main())
