"""Generates src/quotes.h (sleep screen quotes) from a saved A-Z Quotes author page.

    python3 scripts/import_quotes.py "TOP 25 QUOTES BY PAULINE OLIVEROS (of 80) | A-Z Quotes.html" --keep 1,3,4,6,7,9,13,16,17

--keep takes positions on the page (1 = first quote) and leaves out the rest.
The positions above are the quotes on that saved Top 25 page that are about
listening itself.

Takes each quote's text, author and source (the book, when the page names
one), turns typographic punctuation into ASCII (the display fonts have only
ASCII), and leaves out quotes too long for the sleep screen.
"""

import argparse
import html
import os
import re
import sys
from html.parser import HTMLParser

MAX_CHARS = 400  # about ten lines in the small font
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "quotes.h")

ASCII = {
    "‘": "'", "’": "'", "‚": "'", "′": "'",
    "“": '"', "”": '"', "„": '"', "″": '"',
    "–": "-", "—": " - ", "−": "-",
    "…": "...", " ": " ", " ": " ", "​": "",
}


class QuotePage(HTMLParser):
    """Collects (text, author, source) from the page's quote blocks."""

    def __init__(self):
        super().__init__()
        self.quotes = []
        self.field = None  # what the current text belongs to
        self.depth = 0     # nesting inside that field's element
        self.current = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        classes = (a.get("class") or "").split()
        if "wrap-block" in classes:
            self.current = {"text": "", "author": "", "source": ""}
            self.quotes.append(self.current)
        if self.current is None:
            return
        if self.field:
            if tag == "br":
                self.current[self.field] += " "
            elif tag not in ("img", "input", "meta", "link"):
                self.depth += 1
            return
        if tag == "a" and "title" in classes:
            self.field, self.depth = "text", 1
        elif tag == "div" and "author" in classes:
            self.field, self.depth = "author", 1
        elif tag == "span" and "small_source_14" in classes:
            self.field, self.depth = "source", 1

    def handle_endtag(self, tag):
        if self.field:
            self.depth -= 1
            if self.depth == 0:
                self.field = None

    def handle_data(self, data):
        if self.field and self.current is not None:
            self.current[self.field] += data


def ascii_only(text):
    text = html.unescape(text)
    for k, v in ASCII.items():
        text = text.replace(k, v)
    dropped = {c for c in text if ord(c) > 126 or (ord(c) < 32 and c not in "\n\t")}
    text = "".join(c for c in text if c not in dropped)
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"([a-z][.!?])([A-Z])", r"\1 \2", text)  # "space.I want": a lost space after a sentence
    return text, dropped


def source_line(author, source):
    """'Pauline Oliveros, <book title>' when the source names a book in quotes."""
    m = re.search(r'"([^"]+)"', source)
    return f"{author}, {m.group(1)}" if m else author


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("page", help="saved A-Z Quotes author page (.html)")
    parser.add_argument("--keep", help="comma-separated positions of the quotes to use (default: all)")
    args = parser.parse_args()
    keep = {int(n) for n in args.keep.split(",")} if args.keep else None

    page = QuotePage()
    page.feed(open(args.page, encoding="utf-8", errors="replace").read())

    kept, skipped, unchosen, dropped_chars = [], 0, 0, set()
    for position, q in enumerate(page.quotes, 1):
        if keep is not None and position not in keep:
            unchosen += 1
            continue
        text, d1 = ascii_only(q["text"])
        author, d2 = ascii_only(q["author"])
        author = re.split(r"\s+-\s+", author)[0].strip(" ,")  # some blocks repeat the name
        source, d3 = ascii_only(q["source"])
        dropped_chars |= d1 | d2 | d3
        if not text or "Oliveros" not in author:
            continue
        if len(text) > MAX_CHARS:
            skipped += 1
            continue
        kept.append((text, source_line(author, source)))

    if not kept:
        sys.exit("No quotes found; is this an A-Z Quotes author page?")

    with open(OUT, "w") as f:
        f.write("#pragma once\n\n")
        f.write("// Shown at random on the sleep screen. Generated by scripts/import_quotes.py\n")
        f.write(f"// from a saved A-Z Quotes page; edit by hand or run it again.\n\n")
        f.write("struct Quote {\n    const char *text;\n    const char *source;\n};\n\n")
        f.write("static const Quote QUOTES[] = {\n")
        for text, source in kept:
            f.write(f"    {{{c_string(text)},\n     {c_string(source)}}},\n")
        f.write("};\n\nstatic const int QUOTE_COUNT = sizeof(QUOTES) / sizeof(QUOTES[0]);\n")

    print(f"Wrote {len(kept)} quotes to {os.path.normpath(OUT)} "
          f"({unchosen} not chosen, {skipped} too long for the screen, "
          f"{len(page.quotes) - len(kept) - skipped - unchosen} not by Oliveros or empty)")
    if dropped_chars:
        print("Characters the display can't show were left out: " + " ".join(f"U+{ord(c):04X}" for c in sorted(dropped_chars)))


if __name__ == "__main__":
    main()
