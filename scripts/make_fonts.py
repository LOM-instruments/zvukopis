"""Renders the UI fonts (Atkinson Hyperlegible) into Adafruit GFX bitmap fonts.

    pip install freetype-py
    python3 scripts/make_fonts.py "/path/to/Atkinson Hyperlegible Next" "/path/to/Atkinson Hyperlegible Mono"

Writes src/fonts.h. Each font is printable ASCII (the panel's text is ASCII),
rendered at one pixel size with light hinting and thresholded to 1 bit, which
keeps strokes even on the e-paper. Sizes are the em size in pixels.
"""

import os
import sys

import freetype

# (C name, family, file style, em size in px)
FONTS = [
    ("Text17", "Next", "Regular", 17),
    ("Text22", "Next", "Regular", 22),
    ("Medium22", "Next", "Medium", 22),
    ("Bold22", "Next", "Bold", 22),
    ("Bold32", "Next", "Bold", 32),
    ("Bold44", "Next", "Bold", 44),
    ("Italic22", "Next", "RegularItalic", 22),
    ("Italic27", "Next", "RegularItalic", 27),
    ("Italic33", "Next", "RegularItalic", 33),
    ("Italic40", "Next", "RegularItalic", 40),
    ("Mono22", "Mono", "Regular", 22),
]
FIRST, LAST = 0x20, 0x7E
THRESHOLD = 110  # of 255; a little below half keeps thin strokes whole
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "fonts.h")


def render(path, px, name):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, px)
    bits, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        face.load_char(chr(code), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        offset = len(bits) // 8
        for y in range(h):
            for x in range(w):
                bits.append(1 if bm.buffer[y * bm.pitch + x] >= THRESHOLD else 0)
        while len(bits) % 8:
            bits.append(0)  # each glyph starts on a byte
        advance = (g.advance.x + 32) >> 6
        left = g.bitmap_left
        if name == "Mono22" and code == 0x3A:
            # A colon in a full mono cell makes "0:05" read as "0 : 05"; digits stay tabular
            advance, left = 8, 2
        glyphs.append((offset, w, h, advance, left, -g.bitmap_top, code))
    data = bytes(int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))
    line_height = (face.size.height + 32) >> 6
    out = [f"// {os.path.basename(path)} at {px} px\n"]
    out.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{\n")
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
    out.append("};\n\n")
    out.append(f"static const GFXglyph {name}Glyphs[] PROGMEM = {{\n")
    for offset, w, h, adv, xo, yo, code in glyphs:
        c = chr(code).replace("\\", "\\\\")
        out.append(f"    {{{offset}, {w}, {h}, {adv}, {xo}, {yo}}}, // '{c}'\n")
    out.append("};\n\n")
    out.append(f"static const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, "
               f"0x{FIRST:02X}, 0x{LAST:02X}, {line_height}}};\n\n")
    return "".join(out), len(data)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    dirs = {"Next": sys.argv[1], "Mono": sys.argv[2]}
    parts, total = [], 0
    for name, family, style, px in FONTS:
        path = os.path.join(dirs[family], f"AtkinsonHyperlegible{family}-{style}.otf")
        code, size = render(path, px, name)
        parts.append(code)
        total += size
        print(f"{name:12s} {family} {style} {px}px: {size} bytes")
    with open(OUT, "w") as f:
        f.write("#pragma once\n\n")
        f.write("// Atkinson Hyperlegible Next and Mono (Braille Institute of America), as\n")
        f.write("// Adafruit GFX bitmap fonts. Generated by scripts/make_fonts.py; don't edit.\n\n")
        f.write("#include <Adafruit_GFX.h>\n\n")
        f.write("".join(parts))
    print(f"Wrote {os.path.normpath(OUT)} ({total} bytes of glyphs)")


if __name__ == "__main__":
    main()
